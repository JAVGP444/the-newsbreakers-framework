export const MESSAGES: Record<Lang, Dict> = { es, en };

export function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`));
}

export function lookup(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const table = MESSAGES[lang] || MESSAGES.es;
  const raw = table[key] || MESSAGES.es[key] || key;
  return interpolate(raw, vars);
}
